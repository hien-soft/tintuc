/** Từ điển nhãn giao diện (chrome) cho trang công khai. Nội dung bài vẫn là tiếng Việt. */
import type { PublicLocale } from "@/lib/urls";

export const LOCALES: readonly PublicLocale[] = ["vi", "en"];

export function isLocale(value: string): value is PublicLocale {
  return (LOCALES as readonly string[]).includes(value);
}

/** Ép kiểu locale đã được layout kiểm tra; giá trị lạ quy về "vi". */
export function asLocale(value: string): PublicLocale {
  return isLocale(value) ? value : "vi";
}

