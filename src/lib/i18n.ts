/** Đổi tiền tố locale của một đường dẫn công khai (`/vi/...` → `/en/...`). */
export function swapLocale(path: string, locale: PublicLocale): string {
  return path.replace(/^\/(vi|en)(?=\/|$)/, `/${locale}`);
}
